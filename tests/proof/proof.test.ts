import { existsSync, readdirSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  PROOF_MAP,
  checkProofMapFiles,
  parseEvalReport,
  parsePlaywrightJson,
  parseVitestJson,
  renderProof,
  type EvalReport,
  type SuiteResult,
} from "../../scripts/proof-render.ts";

const GOOD_JSON = {
  testResults: [
    {
      name: "/repo/tests/a.test.ts",
      assertionResults: [
        { fullName: "a works", status: "passed" },
        { fullName: "a skipped", status: "skipped" },
      ],
    },
    {
      name: "/repo/tests/b.test.ts",
      assertionResults: [
        { fullName: "b works", status: "passed" },
        { fullName: "b todo", status: "todo" },
      ],
    },
  ],
};

const FAILING_JSON = {
  testResults: [
    {
      name: "/repo/tests/c.test.ts",
      assertionResults: [
        { fullName: "c passes", status: "passed" },
        { fullName: "c breaks", status: "failed" },
      ],
    },
  ],
};

const EVAL_MD = `# Intake evaluation: real model

Run on 2026-11-04. Prompt version \`intake.v1\`. Label: **real-model** (kept apart from the replayed and mocked tests).

## Method

- 19 scenarios.

## openai/gpt-oss-120b (paid)

Scenarios run: 19. Turns: 22. Turns where the model could not be used: 0.
Misses: 1. Violations: 0.
Models that answered: openai/gpt-oss-120b (48 answers).

### Misses (every one)

- \`budget-two-ways\` turn 1 (Budget stated two ways: ask which one is meant): expected ASKED, got PROPOSED

## Choice of the free primary

No free candidate was run.
`;

function suite(over: Partial<SuiteResult> = {}): SuiteResult {
  return {
    id: "unit",
    title: "Unit tests",
    command: "npm run test",
    label: "mocked",
    ran: true,
    files: 2,
    passed: 10,
    failed: 0,
    skipped: 0,
    todo: 0,
    failedTests: [],
    ...over,
  };
}

const EVAL: EvalReport = {
  file: "eval/intake/reports/x.md",
  runOn: "2026-11-04",
  label: "real-model",
  models: [{ model: "openai/gpt-oss-120b (paid)", scenarios: 19, turns: 22, unusable: 0, misses: 1, violations: 0 }],
  missList: ["`budget-two-ways` turn 1 (Budget stated two ways: ask which one is meant): expected ASKED, got PROPOSED"],
};

describe("parseVitestJson", () => {
  it("counts passed, skipped and todo tests and test files", () => {
    expect(parseVitestJson(GOOD_JSON)).toEqual({ files: 2, passed: 2, failed: 0, skipped: 1, todo: 1, failedTests: [] });
  });

  it("names the failing test", () => {
    expect(parseVitestJson(FAILING_JSON)).toMatchObject({ passed: 1, failed: 1, failedTests: ["tests/c.test.ts: c breaks"] });
  });

  it("refuses output that is not a vitest report instead of reporting zeros", () => {
    expect(() => parseVitestJson({})).toThrow(/not a vitest/i);
    expect(() => parseVitestJson(null)).toThrow(/not a vitest/i);
    expect(() => parseVitestJson({ testResults: [] })).toThrow(/no tests/i);
  });
});

describe("parsePlaywrightJson", () => {
  it("reads the stats block", () => {
    expect(parsePlaywrightJson({ stats: { expected: 90, unexpected: 1, skipped: 2, flaky: 0 } })).toMatchObject({ passed: 90, failed: 1, skipped: 2 });
  });

  it("refuses output that is not a Playwright report", () => {
    expect(() => parsePlaywrightJson({})).toThrow(/not a playwright/i);
  });
});

describe("parseEvalReport", () => {
  it("reads the date, label, per-model counts and every miss", () => {
    const r = parseEvalReport(EVAL_MD, "eval/intake/reports/x.md");
    expect(r.runOn).toBe("2026-11-04");
    expect(r.label).toBe("real-model");
    expect(r.models).toEqual([{ model: "openai/gpt-oss-120b (paid)", scenarios: 19, turns: 22, unusable: 0, misses: 1, violations: 0 }]);
    expect(r.missList).toHaveLength(1);
    expect(r.missList[0]).toContain("budget-two-ways");
  });

  it("reads a report with Windows line endings the same way", () => {
    expect(parseEvalReport(EVAL_MD.replace(/\n/g, "\r\n"), "x.md")).toEqual(parseEvalReport(EVAL_MD, "x.md"));
  });

  it("reads every real report in the repository", () => {
    for (const f of readdirSync("eval/intake/reports").filter((n) => n.endsWith(".md"))) {
      expect(() => parseEvalReport(readFileSync(`eval/intake/reports/${f}`, "utf8"), f)).not.toThrow();
    }
  });

  it("throws on a report it cannot read rather than guessing", () => {
    expect(() => parseEvalReport("# nothing here", "x.md")).toThrow(/x\.md/);
  });
});

describe("renderProof", () => {
  const base = { date: "2026-11-06", commit: "abc1234", suites: [suite(), suite({ id: "db", title: "Database tests", command: "npm run test:db", label: "local database" })], evals: [EVAL] };

  it("writes a generated header with the commit and date, and the commands", () => {
    const md = renderProof(base);
    expect(md).toContain("Generated by `npm run proof` on commit `abc1234` on 2026-11-06");
    expect(md).toContain("`npm run test:db`");
  });

  it("shows counts per suite with their label", () => {
    const md = renderProof(base);
    expect(md).toMatch(/Unit tests.*\| 10 \| 0 \| 0 \|/);
    expect(md).toContain("local database");
  });

  it("lists failing tests by name and says the run failed", () => {
    const md = renderProof({ ...base, suites: [suite({ failed: 1, passed: 9, failedTests: ["tests/c.test.ts: c breaks"] })] });
    expect(md).toContain("tests/c.test.ts: c breaks");
    expect(md).toMatch(/FAILING/);
  });

  it("says a suite that did not run was not run, and never prints zeros for it", () => {
    const md = renderProof({ ...base, suites: [suite({ id: "e2e", title: "End-to-end tests", command: "npm run test:e2e", ran: false, passed: 0, files: 0 })] });
    expect(md).toMatch(/End-to-end tests.*not run/i);
    expect(md).not.toMatch(/End-to-end tests.*\| 0 \| 0 \| 0 \|/);
  });

  it("reports the evaluation with its method label and every miss", () => {
    const md = renderProof(base);
    expect(md).toContain("real-model");
    expect(md).toContain("Scenarios 19");
    expect(md).toContain("budget-two-ways");
  });

  it("contains the proof map with every failure mode", () => {
    const md = renderProof(base);
    for (const row of PROOF_MAP) expect(md).toContain(row.failureMode);
  });

  it("states what it did not re-run: the real-sandbox and hosted evidence is hand-written", () => {
    expect(renderProof(base)).toMatch(/not re-run/i);
  });

  it("adds no claim about time saved, demand or accuracy", () => {
    expect(renderProof(base)).not.toMatch(/\b(saves?|faster|accuracy rate|conversion|trusted by)\b/i);
  });
});

describe("PROOF_MAP", () => {
  it("has the five failure modes the spec names", () => {
    expect(PROOF_MAP.map((r) => r.failureMode)).toHaveLength(5);
  });

  it("points only at files that exist", () => {
    expect(checkProofMapFiles(PROOF_MAP, (p) => existsSync(p))).toEqual([]);
  });

  it("reports a renamed file", () => {
    expect(checkProofMapFiles(PROOF_MAP, () => false).length).toBeGreaterThan(0);
  });
});
