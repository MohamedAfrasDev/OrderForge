// Pure report builder for `npm run soak:model`: results in, verdict and markdown out. No network, no files.
// Keep this file to erasable TypeScript (it runs under Node's --experimental-strip-types).

export type SoakOutcome = "answered" | "handoff" | "error";

export type SoakResult = {
  /** 1-based position in the run. */
  index: number;
  /** Wall-clock milliseconds from pressing the button to landing in the order room. */
  ms: number;
  outcome: SoakOutcome;
  /** Short and free of anything the customer typed; for example "the assistant could not answer" or "timeout after 90 s". */
  detail?: string;
};

export type SoakInput = {
  base: string;
  store: string;
  /** The model name as stated by whoever ran the soak: the public flow does not reveal it. */
  modelLabel: string | null;
  startedAt: string;
  results: SoakResult[];
  /** Planned number of requests (a run that stopped early is still reported against the plan). */
  planned: number;
  limitMs: number;
};

export type SoakVerdict = { pass: boolean; answered: number; handoffs: number; errors: number; slow: number; planned: number; slowestMs: number; medianMs: number };

export const DEFAULT_LIMIT_MS = 20_000;

export function judgeSoak(input: Pick<SoakInput, "results" | "planned" | "limitMs">): SoakVerdict {
  const { results, planned, limitMs } = input;
  const answered = results.filter((r) => r.outcome === "answered").length;
  const handoffs = results.filter((r) => r.outcome === "handoff").length;
  const errors = results.filter((r) => r.outcome === "error").length;
  const slow = results.filter((r) => r.ms > limitMs).length;
  const sorted = results.map((r) => r.ms).sort((a, b) => a - b);
  const slowestMs = sorted.length ? sorted[sorted.length - 1]! : 0;
  const mid = Math.floor(sorted.length / 2);
  const medianMs = sorted.length === 0 ? 0 : sorted.length % 2 ? sorted[mid]! : Math.round((sorted[mid - 1]! + sorted[mid]!) / 2);
  // Every planned request must have run, answered, and none may be slow.
  const pass = results.length === planned && planned > 0 && answered === planned && slow === 0;
  return { pass, answered, handoffs, errors, slow, planned, slowestMs, medianMs };
}

const label = (base: string) =>
  /^https?:\/\/(localhost|127\.0\.0\.1|\[::1\])(:|$)/.test(base) ? "**local run, not evidence for the hosted site**" : "**real model, hosted**";
const secs = (ms: number) => `${(ms / 1000).toFixed(1)} s`;

export function renderSoak(input: SoakInput, commit: string | null): string {
  const v = judgeSoak(input);
  const rows = input.results.map((r) => `| ${r.index} | ${secs(r.ms)} | ${r.outcome}${r.detail ? ` (${r.detail})` : ""} |`).join("\n");
  const verdict = v.pass
    ? `**Pass.** ${v.answered} of ${v.planned} requests were answered by the model, none took longer than ${secs(input.limitMs)} (slowest ${secs(v.slowestMs)}, median ${secs(v.medianMs)}).`
    : `**Not a pass.** ${v.answered} of ${v.planned} planned requests were answered (${v.handoffs} ended in the hand-off to the shop, ${v.errors} errors, ${Math.max(0, v.planned - input.results.length)} not run); ${v.slow} took longer than ${secs(input.limitMs)} (slowest ${secs(v.slowestMs)}). No claim of reliability is made from this run.`;
  return `# Model soak

<!-- Generated by \`npm run soak:model\`${commit ? ` on commit ${commit}` : ""}. Do not edit by hand. -->

Label: ${label(input.base)}. Site: \`${input.base}\`. Date: ${input.startedAt}. Store: \`${input.store}\`.

Model: ${input.modelLabel ? `\`${input.modelLabel}\`, as stated by the person who ran this (the public flow does not reveal which model answered)` : "not stated (the public flow does not reveal which model answered)"}.

Method: ${input.planned} requests, one at a time, through the public customer flow in a real browser (open the store page, type a fixed prepared request, press "Start my request", wait for the order room). The time is from the button press to the order room, which the app shows only after the assistant has answered or failed. A request counts as **answered** if the order room shows no hand-off message, **handoff** if it shows that the assistant could not answer, **error** for anything else (a blocked page, a timeout of the browser). The limit for a pass is ${secs(input.limitMs)} each. Each request leaves one throwaway request in the shop's inbox.

## Result

${verdict}

| # | Time | Outcome |
|---|---|---|
${rows}

## What this does not show

It does not measure answer quality (see \`doc/evidence/ai-intake-real-model.md\` for that), it uses one fixed message, and a run of ${input.planned} says how this model behaved at the time of the run, not how it will behave later.
`;
}
